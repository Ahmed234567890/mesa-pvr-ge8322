#!/usr/bin/env python3
"""Generate a libOpenCL forwarding shim for the vendor PowerVR OpenCL library.

Kali's OpenCL applications link against libOpenCL.so.1 (the ICD loader) and
expect a normal glibc library.  The vendor driver is an Android/bionic library,
so it can only be loaded through libhybris.  This generator reads the Khronos
prototypes from cl.h and the exported symbol list of the vendor library, and
emits C wrappers with the exact prototypes that resolve each entry point with
hybris_dlsym() on first use.

Usage:
    gen-opencl-shim.py --header CL/cl.h --symbols symbols.txt --output shim.c

symbols.txt is one exported cl* symbol name per line, for example:
    readelf --dyn-syms -W libPVROCL.so |
        awk '$4 == "FUNC" && $5 == "GLOBAL" && $7 == "DEFAULT" { print $8 }' |
        grep '^cl' > symbols.txt
"""
import argparse
import re
import sys

# Prototypes span lines and end with CL_API_SUFFIX__VERSION_...;
PROTO_RE = re.compile(
    r"extern\s+CL_API_ENTRY\s+(?P<ret>.+?)\s+CL_API_CALL\s*\n?\s*"
    r"(?P<name>\w+)\s*\((?P<args>.*?)\)\s*CL_API_SUFFIX[^;]*;",
    re.DOTALL,
)

FUNC_PTR_RE = re.compile(r"\(\s*[^()]*\*\s*(?P<name>\w+)\s*\)")
TRAILING_NAME_RE = re.compile(r"(?P<name>[A-Za-z_]\w*)\s*(?:\[\s*\])?\s*$")


def split_args(args):
    """Split a parameter list on top-level commas."""
    parts = []
    depth = 0
    current = []
    for ch in args:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def arg_name(arg):
    match = FUNC_PTR_RE.search(arg)
    if match:
        return match.group("name")
    match = TRAILING_NAME_RE.search(arg)
    if match:
        return match.group("name")
    raise ValueError("cannot find a name in parameter %r" % arg)


def parse_prototypes(text):
    prototypes = {}
    for match in PROTO_RE.finditer(text):
        name = match.group("name")
        ret = " ".join(match.group("ret").split())
        args = split_args(match.group("args"))
        if len(args) == 1 and args[0] == "void":
            args = []
        prototypes[name] = (ret, args, arg_name_list(args))
    return prototypes


def arg_name_list(args):
    return [arg_name(a) for a in args]


def emit(prototypes, symbols, header):
    out = []
    out.append("/* Generated by opengl/gen-opencl-shim.py - do not edit. */")
    out.append("/*")
    out.append(" * libOpenCL forwarding shim: every entry point is resolved from the")
    out.append(" * vendor PowerVR OpenCL library through libhybris on first use.")
    out.append(" */")
    out.append("#include <stddef.h>")
    out.append("#include <stdio.h>")
    out.append("#include <stdlib.h>")
    out.append("#include <hybris/common/dlfcn.h>")
    out.append("#include <dlfcn.h>")
    out.append("#define CL_TARGET_OPENCL_VERSION 300")
    out.append("#include <%s>" % header)
    out.append("")
    out.append("#ifndef LIBOPENCL_VENDOR")
    out.append('#define LIBOPENCL_VENDOR "/vendor/lib/libPVROCL.so"')
    out.append("#endif")
    out.append("")
    out.append("static void *vendor_handle;")
    out.append("")
    out.append("static void *vendor_symbol(const char *name)")
    out.append("{")
    out.append("    void *symbol;")
    out.append("")
    out.append("    if (vendor_handle == NULL) {")
    out.append("        const char *path = getenv(\"LIBOPENCL_VENDOR\");")
    out.append("        vendor_handle = hybris_dlopen(path ? path : LIBOPENCL_VENDOR,")
    out.append("                                    RTLD_NOW | RTLD_LOCAL);")
    out.append("        if (vendor_handle == NULL) {")
    out.append("            fprintf(stderr, \"libOpenCL: hybris_dlopen: %s\\n\",")
    out.append("                    hybris_dlerror());")
    out.append("            return NULL;")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    symbol = hybris_dlsym(vendor_handle, name);")
    out.append("    if (symbol == NULL)")
    out.append("        fprintf(stderr, \"libOpenCL: missing vendor symbol %s\\n\", name);")
    out.append("    return symbol;")
    out.append("}")
    out.append("")

    missing = []
    for name in symbols:
        if name in ("clGetExtensionFunctionAddress",
                    "clGetExtensionFunctionAddressForPlatform"):
            continue
        proto = prototypes.get(name)
        if proto is None:
            missing.append(name)
            continue
        ret, args, names = proto
        params = ", ".join(args) if args else "void"
        call = ", ".join(names)
        out.append("typedef %s (CL_API_CALL *fn_%s)(%s);" % (ret, name, params))
        out.append("static fn_%s p_%s;" % (name, name))
        out.append("")
        out.append("CL_API_ENTRY %s CL_API_CALL %s(%s)" % (ret, name, params))
        out.append("{")
        out.append("    if (p_%s == NULL)" % name)
        out.append("        p_%s = (fn_%s)vendor_symbol(\"%s\");" % (name, name, name))
        if ret == "void":
            out.append("    if (p_%s != NULL)" % name)
            out.append("        p_%s(%s);" % (name, call))
        else:
            out.append("    if (p_%s == NULL)" % name)
            out.append("        return (%s)0;" % ret)
            out.append("    return p_%s(%s);" % (name, call))
        out.append("}")
        out.append("")

    # Extension entry point lookup must be forwarded, not resolved by name.
    out.append("CL_API_ENTRY void * CL_API_CALL")
    out.append("clGetExtensionFunctionAddress(const char *name)")
    out.append("{")
    out.append("    typedef void *(CL_API_CALL *fn_t)(const char *);")
    out.append("    static fn_t real;")
    out.append("")
    out.append("    if (real == NULL)")
    out.append("        real = (fn_t)vendor_symbol(\"clGetExtensionFunctionAddress\");")
    out.append("    if (real == NULL)")
    out.append("        return NULL;")
    out.append("    return real(name);")
    out.append("}")
    out.append("")
    out.append("CL_API_ENTRY void * CL_API_CALL")
    out.append("clGetExtensionFunctionAddressForPlatform(cl_platform_id platform,")
    out.append("                                         const char *name)")
    out.append("{")
    out.append("    typedef void *(CL_API_CALL *fn_t)(cl_platform_id, const char *);")
    out.append("    static fn_t real;")
    out.append("")
    out.append("    if (real == NULL)")
    out.append("        real = (fn_t)vendor_symbol(")
    out.append("            \"clGetExtensionFunctionAddressForPlatform\");")
    out.append("    if (real == NULL)")
    out.append("        return NULL;")
    out.append("    return real(platform, name);")
    out.append("}")
    out.append("")

    if missing:
        sys.stderr.write("warning: no prototype for: %s\n" % ", ".join(missing))
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", required=True,
                        help="cl.h path as used in the #include, for example CL/cl.h")
    parser.add_argument("--header-path", required=True,
                        help="filesystem path to the same cl.h")
    parser.add_argument("--symbols", required=True,
                        help="file with one exported cl* symbol per line")
    parser.add_argument("--output", required=True)
    options = parser.parse_args()

    with open(options.header_path) as handle:
        text = handle.read()
    prototypes = parse_prototypes(text)

    with open(options.symbols) as handle:
        symbols = [line.strip() for line in handle if line.strip()]
    symbols = sorted(set(symbols))

    with open(options.output, "w") as handle:
        handle.write(emit(prototypes, symbols, options.header))

    sys.stderr.write("generated %d wrappers\n" % len(symbols))


if __name__ == "__main__":
    main()
